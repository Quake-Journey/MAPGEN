namespace MapgenStudio;

/// <summary>
/// Every text of the interface, in Russian and English (R2), from one table. <see cref="T"/> returns the current
/// language's text; a missing key shows itself as <c>[key]</c> so nothing is silently blank.
/// </summary>
public static class Loc
{
    public static string Language { get; set; } = "ru";

    public static string T(string key) =>
        (Language == "en" ? En : Ru).TryGetValue(key, out var s) ? s
        : Ru.TryGetValue(key, out var r) ? r : $"[{key}]";

    public static string F(string key, params object[] args) => string.Format(T(key), args);

    public static bool Has(string key) => Ru.ContainsKey(key);

    /// <summary>
    /// The gate's key in the string table (S-1, brief 4): the word before its colon, and for the two «pickups»
    /// checks which one it is.
    /// </summary>
    public static string GateKey(string what)
    {
        var colon = what.IndexOf(':');
        var word = (colon > 0 ? what[..colon] : what).Trim().ToLowerInvariant();
        if (word == "pickups")
            word = what.Contains("chaingun", StringComparison.OrdinalIgnoreCase) ? "pickups.chaingun" : "pickups.spawn";
        return "gate." + word;
    }

    /// <summary>A check in plain words; one the table does not know keeps its own line (never silence).</summary>
    public static string Gate(string what) => Has(GateKey(what)) ? T(GateKey(what)) : what;

