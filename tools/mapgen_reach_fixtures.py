"""Small maps that ask the reachability gate one question each.

A gate that only ever runs on q2dm1 proves nothing: q2dm1 passes, and a gate
that returned PASS unconditionally would also pass it. What has to be shown is
that each verdict has a case that produces it and a case that does not, and
that the two differ by ONE thing - a door with a targetname, a lift whose
button was never placed, a destination entity that is not in the map.

So these come in pairs wherever a pair is possible, generated by the same
function with one argument changed, and the guard asserts both halves.

Every fixture is a sealed Valve 220 `.map` the pinned compiler will build
without a leak, with at least two player starts, because the question the gate
asks is about players getting to each other.
"""
from __future__ import annotations

import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))

from mapgen_fixture_lib import (  # noqa: E402
    Box,
    CONTENTS_LAVA,
    CONTENTS_SOLID,
    CONTENTS_WATER,
    Entity,
    MapFixture,
    hollow_room,
)

WALL = "e1u1/c_met5_2"
FLOOR = "e1u1/c_met5_1"
WATER = "e1u1/c_met5_1"


def _spawn(x: float, y: float, z: float) -> Entity:
    return Entity("info_player_deathmatch",
                  keys=[("origin", f"{x:g} {y:g} {z:g}")])


def _floor_with_hole(x0, y0, x1, y1, hx0, hy0, hx1, hy1, z0, z1) -> list[Box]:
    """A slab from (x0,y0) to (x1,y1) with a rectangular hole in it.

    Four boxes rather than one, because a `.map` brush is convex and a slab
    with a hole is not.
    """
    return [
        Box((x0, y0, z0), (x1, hy0, z1), texture=FLOOR),
        Box((x0, hy1, z0), (x1, y1, z1), texture=FLOOR),
        Box((x0, hy0, z0), (hx0, hy1, z1), texture=FLOOR),
        Box((hx1, hy0, z0), (x1, hy1, z1), texture=FLOOR),
    ]


# --------------------------------------------------------------------------
# the control: nothing in the way
# --------------------------------------------------------------------------

def open_room(path: Path) -> None:
    """One room, two starts, no obstacle. The gate must pass this or it is
    broken in a way no other case would show."""
    fx = MapFixture("reach_open_room", "one room, two starts")
    fx.world_brushes = hollow_room((-320, -320, 0), (320, 320, 256),
                                   texture=WALL, floor_texture=FLOOR)
    fx.entities = [_spawn(-192, 0, 32), _spawn(192, 0, 32)]
    path.write_text(fx.emit(), encoding="ascii", newline="\n")


# --------------------------------------------------------------------------
# a pocket a player can fall into and not climb out of
# --------------------------------------------------------------------------

def _pit(name: str, depth: float, lava: bool) -> MapFixture:
    fx = MapFixture(name, "a room with a pit in the floor")
    inner_lo = (-448, -320, -depth)
    inner_hi = (448, 320, 256)
    fx.world_brushes = list(hollow_room(inner_lo, inner_hi, texture=WALL,
                                        floor_texture=FLOOR))
    # The walkable floor at z=0, with a square hole over the pit.
    fx.world_brushes += _floor_with_hole(-448, -320, 448, 320,
                                         -96, -96, 96, 96, -depth, 0)
    if lava:
        fx.world_brushes.append(
            Box((-96, -96, -depth), (96, 96, -depth + 64), texture=FLOOR,
                contents=CONTENTS_LAVA))
    fx.entities = [_spawn(-320, 0, 32), _spawn(320, 0, 32)]
    return fx


def pocket(path: Path) -> None:
    """A dry pit too deep to jump out of: reachable, non-lethal, no exit.
    The gate must FAIL this - it is the defect the whole gate exists for."""
    fx = _pit("reach_pocket", 192.0, lava=False)
    path.write_text(fx.emit(), encoding="ascii", newline="\n")


def lava_pit(path: Path) -> None:
    """The same pit with lava in the bottom. Standing there kills, so it is a
    terminal state and the gate must PASS - otherwise no map with lava in it
    could ever pass and the gate would be useless."""
    fx = _pit("reach_lava_pit", 192.0, lava=True)
    path.write_text(fx.emit(), encoding="ascii", newline="\n")


def step_down(path: Path) -> None:
    """A drop of forty units with a ramp back up. An ordinary piece of level
    design; a gate that calls this a trap cannot be used on anything."""
    fx = MapFixture("reach_step_down", "a low ledge with a way back up")
    fx.world_brushes = list(hollow_room((-448, -320, 0), (448, 320, 256),
                                        texture=WALL, floor_texture=FLOOR))
    # A raised half of the room, and a stair of four steps back onto it.
    fx.world_brushes.append(Box((0, -320, 0), (448, 320, 40), texture=FLOOR))
    for i in range(4):
        fx.world_brushes.append(
            Box((-40 - 40 * i, -64, 0), (0, 64, 40 - 10 * i), texture=FLOOR))
    fx.entities = [_spawn(-320, 0, 32), _spawn(320, 0, 80)]
    path.write_text(fx.emit(), encoding="ascii", newline="\n")


