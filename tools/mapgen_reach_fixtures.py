# --------------------------------------------------------------------------
# a route that exists only by riding a train
# --------------------------------------------------------------------------

def _train_over_lava(name: str, blocked: bool) -> MapFixture:
    """Two ledges over lava, three hundred and twenty units apart.

    Nobody jumps that. The only way across is the platform that runs between
    them, so the map is a statement about one machine: if it cannot travel,
    the far half of the level does not exist.
    """
    fx = MapFixture(name, "two ledges over lava joined only by a train")
    fx.world_brushes = list(hollow_room((-768, -192, 0), (768, 192, 384),
                                        texture=WALL, floor_texture=FLOOR))
    fx.world_brushes += [
        # The right ledge begins where the platform ENDS, not where it stops:
        # a machine whose far stop is inside the thing it is arriving at has
        # nowhere to arrive, and the first version of this fixture was that.
        Box((-768, -192, 0), (-160, 192, 96), texture=FLOOR),
        Box((224, -192, 0), (768, 192, 96), texture=FLOOR),
        Box((-160, -192, 0), (224, 192, 64), texture=FLOOR,
            contents=CONTENTS_LAVA),
    ]
    if blocked:
        # A beam across the shaft the train runs through. Both ledges are
        # exactly where they were; the machine is what changed.
        fx.world_brushes.append(
            Box((-16, -96, 64), (16, 96, 256), texture=WALL))

    fx.entities = [
        Entity("func_train",
               keys=[("target", "corner_a"), ("speed", "100")],
               brushes=[Box((-160, -64, 80), (-96, 64, 96), texture=FLOOR)]),
        Entity("path_corner", keys=[("targetname", "corner_a"),
                                    ("target", "corner_b"),
                                    ("origin", "-160 -64 80")]),
        Entity("path_corner", keys=[("targetname", "corner_b"),
                                    ("target", "corner_a"),
                                    ("origin", "160 -64 80")]),
        _spawn(-512, 0, 128),
        _spawn(512, 0, 128),
    ]
    return fx


def train(path: Path) -> None:
    """The train runs. Both halves of the map are one place."""
    fx = _train_over_lava("reach_train", False)
    path.write_text(fx.emit(), encoding="ascii", newline="\n")


