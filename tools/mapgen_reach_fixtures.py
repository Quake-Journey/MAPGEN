def _alcove(name: str, opening: float) -> MapFixture:
    """A chamber, and an alcove off it behind a wall with a gap in it.

    `opening` is how tall that gap is, and it is the only difference between
    the two halves: a doorway he walks through, or a slot he can see the
    weapon through and never reach. He cannot reach through it either - a
    player and a pickup are both thirty-two units wide, so no wall can stand
    between their boxes and still let them touch.
    """
    fx = MapFixture(name, "an alcove behind a gap in a wall")
    fx.world_brushes = list(hollow_room((-448, -320, 0), (448, 320, 256),
                                        texture=WALL, floor_texture=FLOOR))
    # The dividing wall at x = 128, solid but for one gap in the middle of it
    # running from the floor up to `opening`.
    fx.world_brushes.append(Box((128, -320, 0), (160, -64, 256), texture=WALL))
    fx.world_brushes.append(Box((128, 64, 0), (160, 320, 256), texture=WALL))
    fx.world_brushes.append(Box((128, -64, opening), (160, 64, 256),
                                texture=WALL))
    fx.entities = [
        Entity("weapon_rocketlauncher", keys=[("origin", "176 0 24")]),
        _spawn(-320, 0, 32),
        _spawn(-320, 224, 32),
    ]
    return fx


