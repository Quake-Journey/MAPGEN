def _two_rooms_and_a_door(name: str, targetname: str | None) -> MapFixture:
    fx = MapFixture(name, "two rooms joined only by a door")
    fx.world_brushes = list(hollow_room((-512, -128, 0), (512, 128, 192),
                                        texture=WALL, floor_texture=FLOOR))
    # A dividing wall with a doorway 64 wide and 96 tall.
    fx.world_brushes += [
        Box((-16, -128, 0), (16, -32, 192), texture=WALL),
        Box((-16, 32, 0), (16, 128, 192), texture=WALL),
        Box((-16, -32, 96), (16, 32, 192), texture=WALL),
    ]
    keys = [("angle", "-1"), ("lip", "8"), ("speed", "100")]
    if targetname:
        keys.append(("targetname", targetname))
    fx.entities = [
        Entity("func_door", keys=keys,
               brushes=[Box((-16, -32, 0), (16, 32, 96), texture=WALL)]),
        _spawn(-320, 0, 32),
        _spawn(320, 0, 32),
    ]
    return fx


def door(path: Path) -> None:
    """A door anyone can walk up to. The route exists and the gate must pass."""
    fx = _two_rooms_and_a_door("reach_door", None)
    path.write_text(fx.emit(), encoding="ascii", newline="\n")


