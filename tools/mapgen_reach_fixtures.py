# --------------------------------------------------------------------------
# a frontier wide enough that the walk really does split
# --------------------------------------------------------------------------

def wide_hall(path: Path) -> None:
    """A pillared hall with machines around it.

    Every other fixture here is a narrow frontier: a few rooms, never eight
    states in a level, and the walk stays on one thread however many workers it
    is given. So the whole sequential-against-parallel matrix was, on all of
    them, one thread agreeing with one thread.

    A grid of pillars is the cheapest wide frontier there is - from anywhere
    inside it the search can go many ways at once - and the machines around the
    edge put movers, a teleporter and items into what the threads share.
    """
    fx = MapFixture("reach_wide_hall",
                    "a pillared hall, wide enough to walk in parallel")

    HALF, TOP, T = 768, 320, 16

    # The hall, without its east wall: that side is built by hand below,
    # because it needs a doorway in it.
    fx.world_brushes = list(hollow_room((-HALF, -HALF, 0), (HALF, HALF, TOP),
                                        texture=WALL, floor_texture=FLOOR,
                                        omit="east"))

    # Twenty-five pillars on a 256-unit grid, each 64 across. They divide the
    # floor into a lattice of ways round, which is what makes the frontier
    # wide, and they run floor to ceiling so each one is a real obstacle.
    for gx in range(-2, 3):
        for gy in range(-2, 3):
            cx, cy = gx * 256, gy * 256
            fx.world_brushes.append(Box((cx - 32, cy - 32, 0),
                                        (cx + 32, cy + 32, TOP),
                                        texture=WALL))

    # The east wall, with a doorway 128 wide and 96 tall, and the side room
    # behind it. The room's own west slab is omitted: this wall IS it.
    fx.world_brushes += [
        Box((HALF, -HALF - T, 0), (HALF + T, -64, TOP), texture=WALL),
        Box((HALF, 64, 0), (HALF + T, HALF + T, TOP), texture=WALL),
        Box((HALF, -64, 96), (HALF + T, 64, TOP), texture=WALL),
    ]
    fx.world_brushes += list(hollow_room((HALF + T, -192, 0),
                                         (HALF + T + 384, 192, TOP),
                                         texture=WALL, floor_texture=FLOOR,
                                         omit="west"))

    fx.entities = [
        _spawn(-640, -640, 32),
        _spawn(640, 640, 32),
        _spawn(-640, 640, 32),
        _spawn(640, -640, 32),
        # A door that only a button opens, so a mover round is part of what
        # the threads are working on rather than a footnote.
        Entity("func_door",
               keys=[("angle", "-1"), ("lip", "8"), ("speed", "100"),
                     ("targetname", "hall_door")],
               brushes=[Box((HALF, -64, 0), (HALF + T, 64, 96),
                            texture=WALL)]),
        Entity("func_button",
               keys=[("angle", "0"), ("lip", "4"), ("speed", "40"),
                     ("target", "hall_door"), ("wait", "3")],
               brushes=[Box((-HALF, 480, 32), (-HALF + 8, 512, 64),
                            texture=WALL)]),
        # A second kind of machine.
        #
        # Drawn at the TOP of its travel, which is where Q2 spawns a plat: a
        # plat with nothing targeting it drops to `height` below where it was
        # drawn and waits there for a rider. Drawn on the floor it would rest
        # inside the floor slab, be obstructed for its whole travel, and count
        # as a machine nothing can operate - which is exactly what the gate
        # said the first time this fixture was walked.
        Entity("func_plat",
               keys=[("speed", "80"), ("height", "128")],
               brushes=[Box((-160, -160, 128), (-96, -96, 144),
                            texture=WALL)]),
        # And a way across the hall that is not walking.
        Entity("trigger_teleport", keys=[("target", "hall_exit")],
               brushes=[Box((-704, -32, 0), (-640, 32, 64), texture=WALL)]),
        Entity("info_teleport_destination",
               keys=[("origin", "704 0 32"), ("targetname", "hall_exit")]),
        Entity("item_health", keys=[("origin", "-384 -384 32")]),
        Entity("item_health", keys=[("origin", "384 384 32")]),
        Entity("item_armor_body", keys=[("origin", "-384 384 32")]),
        Entity("weapon_rocketlauncher", keys=[("origin", "384 -384 32")]),
        Entity("light", keys=[("origin", "0 0 280"), ("light", "500")]),
    ]
    path.write_text(fx.emit(), encoding="ascii", newline="\n")


